const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {chromium}=require('playwright');
(async()=>{
  const browser=await chromium.launch({headless:true,channel:'msedge'});
  try{
    const page=await browser.newPage({viewport:{width:1280,height:1000}}),errors=[],writes=[];
    page.on('pageerror',e=>errors.push(e.message));
    let auto={available:true,status:'idle',message:'Ready for measurement',profiles:[],audio_owned:false,running:false,selected_pairs:['a','sub','tweeter'],test_attenuation_db:0};
    await page.route('http://octet.test/**',async route=>{
      const p=new URL(route.request().url()).pathname;
      if(p==='/api/auto')return route.fulfill({json:auto});
      if(p==='/api/dsp')return route.fulfill({json:{profile:'Manual',volume:-36,max_db:-18,sample_rate:48000,muted:true,channels:[]}});
      if(p.startsWith('/api/control/auto-')){
        const body=route.request().postDataJSON();writes.push([p,body]);
        if(p.endsWith('start'))auto={...auto,status:'running',stage:'levels',message:'L_a: −54 dBFS',audio_owned:true,running:true,peak_db:-42};
        else if(p.endsWith('stop'))auto={...auto,status:'cancelled',message:'Stopped',running:false};
        else if(p.endsWith('restore'))auto={...auto,status:'idle',message:'Previous settings restored',audio_owned:false};
        else if(p.endsWith('select'))auto={...auto,active:auto.profiles[0],message:'Saved profile applied'};
        else if(p.endsWith('test-level'))auto={...auto,test_attenuation_db:body.test_attenuation_db,message:'Test attenuation saved'};
        return route.fulfill({json:auto});
      }
      const file=p==='/dsp'?'dsp.html':p.slice(1);
      if(!['dsp.html','dsp.js','volume.js','auto.js','measurements.js','style.css'].includes(file))return route.fulfill({status:404,body:''});
      return route.fulfill({body:fs.readFileSync(path.join(__dirname,file)),contentType:file.endsWith('html')?'text/html':file.endsWith('js')?'text/javascript':'text/css'});
    });
    await page.goto('http://octet.test/dsp');
    await page.getByRole('button',{name:'Start Auto mode'}).waitFor();
    await page.waitForFunction(()=>!document.getElementById('auto-start').disabled);
    assert.equal(await page.locator('input[name="auto-pair"][value="b"]').isChecked(),false);
    await page.locator('input[name="auto-pair"][value="a"]').uncheck();
    assert.equal(await page.locator('#auto-start').isDisabled(),true,'An exciter pair is required');
    await page.locator('input[name="auto-pair"][value="a"]').check();
    await page.getByRole('button',{name:'Start Auto mode'}).click();
    assert.equal(writes.length,0,'Mic readiness must be required');
    await page.locator('#auto-test-attenuation').fill('-1');
    await page.getByRole('button',{name:'Save test level',exact:true}).click();
    assert.equal(writes.length,0,'Negative attenuation must not boost the test');
    await page.locator('#auto-test-attenuation').fill('9');
    await page.getByRole('button',{name:'Save test level',exact:true}).click();
    await page.waitForFunction(()=>document.getElementById('auto-status').textContent==='Test attenuation saved');
    assert.deepEqual(writes[0],['/api/control/auto-test-level',{test_attenuation_db:9}]);
    assert.equal(auto.running,false,'Saving the level must not play tones');
    await page.reload();
    await page.waitForFunction(()=>document.getElementById('auto-test-attenuation').value==='9');
    await page.locator('#auto-ready').check();await page.locator('#auto-name').fill('Chair');
    await page.getByRole('button',{name:'Start Auto mode'}).click();
    await page.waitForFunction(()=>document.getElementById('auto-status').textContent.includes('L_a'));
    assert.deepEqual(writes[1][1],{name:'Chair',microphone_ready:true,selected_pairs:['a','sub','tweeter'],test_attenuation_db:9});
    assert.equal(await page.locator('#auto-test-attenuation').isDisabled(),true);
    assert.equal(await page.locator('#auto-test-save').isDisabled(),true);
    assert.equal(await page.locator('input[name="auto-pair"][value="a"]').isDisabled(),true);
    assert.equal(await page.locator('#volume').isDisabled(),true);
    await page.getByRole('button',{name:'Stop tones',exact:true}).last().click();
    await page.waitForFunction(()=>document.getElementById('auto-status').textContent==='Stopped');
    auto.profiles=[{id:'saved',name:'Chair',created:'2026-10-20',playback_max_db:-10,preamp_db:{L:-18.8,R:-16.1},selected_pairs:['a','sub','tweeter'],chosen:Object.fromEntries(['L','R'].map(side=>[side,{low:300,high:4000,order:4}]))}];
    await page.waitForFunction(()=>!document.getElementById('auto-restore').disabled);
    await page.getByRole('button',{name:'Restore before tuning'}).click();
    await page.waitForFunction(()=>!document.getElementById('auto-select').disabled);
    await page.getByRole('button',{name:'Apply profile',exact:true}).click();
    await page.waitForFunction(()=>document.getElementById('auto-status').textContent==='Saved profile applied');
    assert.equal(writes.at(-1)[1].id,'saved');
    assert.match(await page.locator('#auto-summary').innerText(),/Music output ceiling: -10 dBFS/);
    assert.match(await page.locator('#auto-summary').innerText(),/L -18.8 dB/);
    auto.active.stereo_verification={passed:true,right_minus_left_ms:.01,right_minus_left_db:.1};
    await page.waitForFunction(()=>document.getElementById('auto-summary').textContent.includes('Stereo timing, balance and polarity verified'));
    await page.evaluate(()=>window.renderTunedOutputs({tuning:{selected_pairs:['a','sub','tweeter'],chosen:Object.fromEntries(['L','R'].map(side=>[side,{low:400,high:4200,order:4,gains:{a:0,sub:-3,tweeter:-6},delays:{a:0,sub:1,tweeter:2},polarity:{a:1,sub:1,tweeter:1}}]))}}));
    assert.equal(await page.locator('#channels article').count(),8);
    assert.match(await page.locator('#channels article').nth(2).innerText(),/output muted/);
    assert.match(await page.locator('#channels article').nth(3).innerText(),/output muted/);
    await page.evaluate(()=>window.renderTunedOutputs({tuning:{selected_pairs:['a'],stereo:{L:{delay_ms:2.25,gain_db:-3,polarity:-1}},chosen:Object.fromEntries(['L','R'].map(side=>[side,{low:400,high:4200,order:4,gains:{a:0},delays:{a:0},polarity:{a:1}}]))}}));
    assert.match(await page.locator('#channels article').first().innerText(),/-3.0 dB relative attenuation · 2.25 ms delay · inverted polarity/);
    auto.failed_drivers={L_b:{output:3,reason:'Insufficient microphone signal.'}};
    await page.waitForFunction(()=>!document.getElementById('auto-skipped').hidden);
    assert.match(await page.locator('#auto-skipped-list').innerText(),/Output 3: Insufficient microphone signal/);
    await page.evaluate(()=>window.renderTunedOutputs({tuning:{selected_pairs:['a','b'],active_driver_ids:['L_a','R_a','R_b'],failed_drivers:{L_b:{output:3,reason:'Insufficient microphone signal.'}},chosen:{L:{active_pairs:['a'],low:150,high:12000,order:4,gains:{a:0},delays:{a:0},polarity:{a:1}},R:{active_pairs:['a','b'],low:150,high:12000,order:4,gains:{a:0,b:-3},delays:{a:0,b:1},polarity:{a:1,b:1}}}}}));
    assert.match(await page.locator('#channels article').nth(2).innerText(),/Measurement skipped · output muted/);
    assert.match(await page.locator('#channels article').nth(3).innerText(),/-3.0 dB relative attenuation/);
    assert.doesNotMatch(await page.locator('#channels article').nth(3).innerText(),/output muted/);
    await page.setViewportSize({width:390,height:844});
    assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Mobile layout overflows');
    await page.screenshot({path:path.join(__dirname,'../../out/test-attenuation-mobile.png'),fullPage:true});
    assert.deepEqual(errors,[]);
    console.log('Auto mode browser checks passed: mic readiness, start, progress, output lock, stop, recovery, recall, mobile layout.');
  }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exit(1)});
